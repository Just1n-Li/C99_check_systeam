/* 验证 C99 6.5.2.1 Array subscripting */
/* 预期：正向测试运行通过，负向测试编译报错 */

#include <stdio.h>
#include <assert.h>

/* ========== 正向测试：以下代码应能编译并运行通过 ========== */

int main(void) {
    /* [1] 约束：一个表达式是指向对象类型的指针，另一个是整数类型 */
    int arr[5] = {10, 20, 30, 40, 50};
    int *p = arr;

    /* [2] 语义：E1[E2] 等同于 *((E1)+(E2)) */
    assert(arr[2] == 30);
    assert(*((arr) + (2)) == 30);

    /* [2] 语义：由于加法交换律，E2[E1] 也合法 */
    assert(2[arr] == 30);

    /* [1] 约束：指针作为左操作数，整数作为右操作数 */
    assert(p[3] == 40);
    /* [1] 约束：整数作为左操作数，指针作为右操作数 */
    assert(3[p] == 40);

    /* [3][4] 语义：多维数组的连续下标 */
    int x[3][5];
    int count = 0;
    for (int i = 0; i < 3; i++) {
        for (int j = 0; j < 5; j++) {
            x[i][j] = count++;
        }
    }
    assert(x[0][0] == 0);
    assert(x[1][2] == 7);
    assert(x[2][4] == 14);

    /* [3] 语义：数组按行优先顺序存储（最后一个下标变化最快） */
    int y[2][3] = {{1, 2, 3}, {4, 5, 6}};
    int *yp = &y[0][0];
    assert(yp[0] == 1);
    assert(yp[1] == 2);
    assert(yp[2] == 3);
    assert(yp[3] == 4);
    assert(yp[4] == 5);
    assert(yp[5] == 6);

    /* [4] 例子：x 转换为指向初始 5-int 数组的指针，x+1 指向 x[1] */
    int (*row)[5] = x + 1;
    assert((*row)[2] == x[1][2]);

    /* [3] 语义：x[i] 作为非左值转换为指向 int 的指针 */
    int *elem = x[1];
    assert(elem[2] == x[1][2]);

    /* [3] 语义：显式应用一元 * 操作符，结果为 (n-1) 维数组 */
    assert((*(x + 2))[3] == x[2][3]);

    printf("All positive tests passed.\n");
    return 0;
}

